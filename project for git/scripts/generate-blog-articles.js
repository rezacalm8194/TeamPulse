function sitemapXml() {
  const staticUrls = [
    ["https://teampulse.ir/", "1.0", "weekly"],
    ["https://teampulse.ir/privacy.html", "0.4", "monthly"],
    ["https://teampulse.ir/blog/", "0.8", "weekly"]
  ];
  const urls = staticUrls.concat(articles.map((article) => [`https://teampulse.ir/blog/${article.slug}.html`, "0.7", "monthly"]));
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(([loc, priority, changefreq]) => `  <url>
    <loc>${loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`).join("\n")}
</urlset>
`;
}

